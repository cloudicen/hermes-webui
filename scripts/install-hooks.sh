#!/usr/bin/env bash
# install-hooks.sh — install the hermes-webui local CI gate hooks.
#
# Mirrors the upstream GitHub Actions jobs (.github/workflows/tests.yml) as git
# hooks so contributors run the same gates locally instead of waiting for CI.
# Idempotent: safe to rerun at any time.
#
# What it does:
#   1. Resolves the base Python for ./scripts/test.sh and writes/strips
#      scripts/ci/env.local accordingly (gitignored, per-machine).
#   2. Appends scripts/ci/env.local to .gitignore if not already ignored.
#   3. Sets git config core.hooksPath=scripts/ci (printing any previous value).
#   4. chmod +x the hooks, then runs scripts/ci/pre-commit once as a self-check.
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ROOT="$(cd "$SCRIPT_DIR/.." && pwd)"

if ! git -C "$ROOT" rev-parse --show-toplevel >/dev/null 2>&1; then
  echo "install-hooks.sh: $ROOT is not a git worktree — aborting." >&2
  exit 1
fi
# The hooks are addressed relative to the worktree root (core.hooksPath is
# resolved from where git runs hooks = the top level), so operate from there.
if [[ "$(pwd)" != "$ROOT" ]]; then
  echo "INFO  invoked from $(pwd); continuing against the repo root: $ROOT"
  cd "$ROOT"
fi

ENV_LOCAL_FILE="$ROOT/scripts/ci/env.local"
HOOKS_DIR="$ROOT/scripts/ci"

for f in lib.sh pre-commit pre-push; do
  if [[ ! -f "$HOOKS_DIR/$f" ]]; then
    echo "install-hooks.sh: missing $HOOKS_DIR/$f — the hooks must ship with the repo." >&2
    exit 1
  fi
done

# Supported = 3.11-3.13, the range scripts/test.sh (and CI) accept.
supported_python() {
  "$1" - <<'PY' >/dev/null 2>&1
import sys
raise SystemExit(0 if (3, 11) <= sys.version_info[:2] <= (3, 13) else 1)
PY
}

# Dry replica of scripts/test.sh find_supported_base_python: would test.sh
# auto-find a supported interpreter on PATH without any override?
find_auto_python() {
  local candidate path
  for candidate in python3.13 python3.12 python3.11 python3; do
    path="$(command -v "$candidate" 2>/dev/null || true)"
    if [[ -n "$path" && -x "$path" ]] && supported_python "$path"; then
      printf '%s\n' "$path"
      return 0
    fi
  done
  return 1
}

# --- (a) env.local: pin or unpin HERMES_WEBUI_TEST_PYTHON ----------------------
ensure_env_local() {
  local auto_py uv_py candidate
  if auto_py="$(find_auto_python)"; then
    # Auto-detect works — env.local must NOT pin a base interpreter: a stale
    # pin from a previous machine state would override a working auto-detect.
    if [[ -f "$ENV_LOCAL_FILE" ]] && grep -qE '^[[:space:]]*(export[[:space:]]+)?HERMES_WEBUI_TEST_PYTHON=' "$ENV_LOCAL_FILE"; then
      local tmp
      tmp="$(mktemp)"
      grep -vE '^[[:space:]]*(export[[:space:]]+)?HERMES_WEBUI_TEST_PYTHON=' "$ENV_LOCAL_FILE" >"$tmp" || true
      if grep -qE '^[[:space:]]*[^#[:space:]][^#]*=' "$tmp"; then
        # Other user overrides remain — keep the file without the pin.
        mv "$tmp" "$ENV_LOCAL_FILE"
        echo "INFO  removed stale HERMES_WEBUI_TEST_PYTHON from scripts/ci/env.local (auto-detect finds $auto_py)."
      else
        # Nothing meaningful left — drop the file entirely.
        rm -f "$tmp" "$ENV_LOCAL_FILE"
        echo "INFO  removed scripts/ci/env.local (it only held a now-unneeded HERMES_WEBUI_TEST_PYTHON pin; auto-detect finds $auto_py)."
      fi
    else
      echo "INFO  Python auto-detect OK ($auto_py) — no HERMES_WEBUI_TEST_PYTHON override needed."
    fi
    return 0
  fi

  # Auto-detect failed (e.g. system python3 is 3.10). Find a supported
  # interpreter: uv-managed CPython first, then python3.11 on PATH (absolute
  # only — a relative entry would break test.sh's later invocations).
  uv_py=""
  for candidate in "$HOME"/.local/share/uv/python/*/bin/python3.11; do
    if [[ -x "$candidate" ]] && supported_python "$candidate"; then
      uv_py="$(readlink -f "$candidate" 2>/dev/null || printf '%s' "$candidate")"
      break
    fi
  done
  if [[ -z "$uv_py" ]]; then
    candidate="$(command -v python3.11 2>/dev/null || true)"
    if [[ -n "$candidate" && "$candidate" == /* && -x "$candidate" ]] && supported_python "$candidate"; then
      uv_py="$candidate"
    fi
  fi
  if [[ -z "$uv_py" ]]; then
    cat >&2 <<EOF
install-hooks.sh: no supported Python (3.11-3.13) found:
  - not on PATH (checked python3.13, python3.12, python3.11, python3)
  - not under \$HOME/.local/share/uv/python/*/bin/python3.11
Install Python 3.11-3.13 (or uv: https://docs.astral.sh/uv/) and rerun this script.
Aborting — the test hooks cannot work without a supported interpreter.
EOF
    return 1
  fi

  cat >"$ENV_LOCAL_FILE" <<EOF
# Generated by scripts/install-hooks.sh — per-machine overrides for the local CI
# hooks (gitignored; safe to edit by hand; rerun the installer to regenerate).
#
# scripts/test.sh could not auto-find a supported Python (3.11-3.13) on PATH,
# so the base interpreter used to create/rebuild the repo .venv is pinned here:
export HERMES_WEBUI_TEST_PYTHON=$uv_py
EOF
  echo "INFO  wrote scripts/ci/env.local with HERMES_WEBUI_TEST_PYTHON=$uv_py"
}

# --- (gitignore guard) ----------------------------------------------------------
ensure_gitignore_line() {
  if grep -qxF 'scripts/ci/env.local' "$ROOT/.gitignore"; then
    echo "INFO  .gitignore already ignores scripts/ci/env.local."
  else
    printf '%s\n' 'scripts/ci/env.local' >>"$ROOT/.gitignore"
    echo "INFO  appended scripts/ci/env.local to .gitignore."
  fi
}

main() {
  echo "== Hermes WebUI local CI hook installer =="

  ensure_env_local
  ensure_gitignore_line

  local old
  old="$(git -C "$ROOT" config --get core.hooksPath || true)"
  if [[ -n "$old" && "$old" != "scripts/ci" ]]; then
    echo "INFO  overwriting existing core.hooksPath='$old' (revert later with: git config --unset core.hooksPath)"
  fi
  git -C "$ROOT" config core.hooksPath scripts/ci
  echo "INFO  git config core.hooksPath = $(git -C "$ROOT" config --get core.hooksPath)"

  chmod +x "$HOOKS_DIR/pre-commit" "$HOOKS_DIR/pre-push" "$HOOKS_DIR/lib.sh"
  echo "INFO  chmod +x scripts/ci/{lib.sh,pre-commit,pre-push}"

  echo
  echo "== Self-check: running scripts/ci/pre-commit once =="
  local selfcheck=ok
  if ! "$HOOKS_DIR/pre-commit"; then
    selfcheck=failed
  fi

  echo
  echo "== Summary =="
  cat <<EOF
Installed gates (run by git via core.hooksPath=scripts/ci):
  pre-commit : compileall whole-tree syntax gate, ruff forward gate
               (committed + staged content, vs origin/master), ESLint runtime
               guard + scope_undef gate when static JS is staged
  pre-push   : the same cheap gates rerun (no --no-verify escape hatch), then
               the FULL pytest suite sharded across HERMES_WEBUI_TEST_SHARDS
               processes, then optional browser smoke
EOF
  if [[ -f "$ENV_LOCAL_FILE" ]]; then
    echo "scripts/ci/env.local (gitignored, per-machine):"
    sed 's/^/    /' "$ENV_LOCAL_FILE"
  else
    echo "scripts/ci/env.local: absent (no per-machine overrides needed)."
  fi
  cat <<'EOF'
Skip / tuning variables (export in your shell or scripts/ci/env.local):
  HERMES_WEBUI_SKIP_HOOKS=1          bypass EVERYTHING (both hooks; prints a warning)
  HERMES_WEBUI_SKIP_PY_LINT=1        bypass compileall + ruff gates
  HERMES_WEBUI_SKIP_JS=1             bypass the ESLint runtime guards
  HERMES_WEBUI_SKIP_TESTS=1          bypass the full pytest gate (pre-push)
  HERMES_WEBUI_SKIP_BROWSER_SMOKE=1  bypass browser smoke even when opted in
  HERMES_WEBUI_TEST_SHARDS=<int>     pre-push shard count (default: min(8, nproc),
                                     capped by available memory to avoid OOM)
  HERMES_WEBUI_PUSH_PYTEST_ARGS="..."  pytest args override
                                     (default: "tests/ -q --timeout=60")
  HERMES_WEBUI_PUSH_BROWSER_SMOKE=1  opt IN to browser smoke: installs
                                     playwright + chromium in .venv if missing,
                                     then runs tests/browser_smoke.py

Uninstall:
  git config --unset core.hooksPath
  (optionally: rm scripts/ci/env.local)

Note: the first pre-push creates nothing new (the .venv is already ensured by
this installer's self-check), but it runs the FULL suite — expect minutes, not
seconds. Shards default to min(8, nproc) parallel pytest processes.
EOF
  if [[ "$selfcheck" != ok ]]; then
    echo
    echo "install-hooks.sh: self-check FAILED — hooks are installed, but the pre-commit gates did not pass. Fix the reported failure before committing." >&2
    exit 1
  fi
  echo
  echo "Install OK — self-check passed. Hooks are live."
}

main "$@"
