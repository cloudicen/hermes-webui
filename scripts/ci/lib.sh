#!/usr/bin/env bash
# lib.sh — shared helpers for the hermes-webui local CI hooks (scripts/ci/pre-commit,
# scripts/ci/pre-push). Sourced by those hooks; not meant to be executed directly.
#
# The hooks mirror .github/workflows/tests.yml so a developer catches locally the
# same failures GitHub Actions would report after the push. Keep every gate here
# in lockstep with the workflow step it mirrors.

# --- repo root + venv resolution (CWD-independent: anchored to this file) -----

CI_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ROOT="$(cd "$CI_DIR/../.." && pwd)"

# Fail closed if this is somehow not a git worktree: a hook that cannot locate
# the repo cannot guarantee any gate actually ran against it.
if ! git -C "$ROOT" rev-parse --show-toplevel >/dev/null 2>&1; then
  echo "ci lib: $ROOT is not a git worktree — cannot run the local CI gates." >&2
  exit 1
fi

VENV_DIR="$ROOT/.venv"

resolve_venv_python() {
  local candidate
  for candidate in "$VENV_DIR/bin/python" "$VENV_DIR/Scripts/python.exe"; do
    if [[ -x "$candidate" ]]; then
      printf '%s\n' "$candidate"
      return 0
    fi
  done
  return 1
}

VENV_PY="$(resolve_venv_python || true)"

# Per-machine overrides for these hooks (gitignored; generated by
# scripts/install-hooks.sh, safe to hand-edit). Typically pins
# HERMES_WEBUI_TEST_PYTHON so scripts/test.sh can build the .venv on machines
# whose system python3 falls outside the supported 3.11-3.13 range.
ENV_LOCAL="$CI_DIR/env.local"
if [[ -f "$ENV_LOCAL" ]]; then
  # shellcheck disable=SC1090
  source "$ENV_LOCAL"
fi

# --- logging -------------------------------------------------------------------
# PASS/INFO/SKIP to stdout; WARN/FAIL to stderr so git surfaces them even when
# it otherwise quiesces hook output.

ci_pass() { printf 'PASS  %s\n' "$*"; }
ci_info() { printf 'INFO  %s\n' "$*"; }
ci_skip() { printf 'SKIP  %s\n' "$*"; }
ci_warn() { printf 'WARN  %s\n' "$*" >&2; }
ci_fail() { printf 'FAIL  %s\n' "$*" >&2; }

# --- skip controls --------------------------------------------------------------

# Truthy values follow the repo convention (README: HERMES_WEBUI_SSE_CHUNKED
# and friends accept 1/true/yes/on).
ci_skip_requested() {
  local val="${!1:-}"
  case "$val" in
    1|[Tt][Rr][Uu][Ee]|[Yy][Ee][Ss]|[Oo][Nn]) return 0 ;;
    *) return 1 ;;
  esac
}

# --- node -----------------------------------------------------------------------

node_major_version() {
  node --version 2>/dev/null | sed -e 's/^v//' -e 's/\..*//'
}

# CI pins Node 20 for the ESLint runtime guards (eslint ^10 requires >= 20). On
# an older Node the gates would die with a misleading engine error — callers
# fail closed with guidance instead of letting that noise through.
node_version_ok() {
  command -v node >/dev/null 2>&1 || return 1
  local major
  major="$(node_major_version)"
  [[ "$major" =~ ^[0-9]+$ ]] || return 1
  (( major >= 20 ))
}

# --- python ---------------------------------------------------------------------

# Best interpreter for the whole-tree syntax gate: the repo venv when present,
# otherwise any python3 (compileall is syntax-only, so an older-but-present
# python3 is acceptable for that gate specifically).
ci_python() {
  if [[ -n "${VENV_PY:-}" ]]; then
    printf '%s\n' "$VENV_PY"
  else
    command -v python3 || printf 'python3\n'
  fi
}

_ci_venv_guidance() {
  ci_fail "could not ensure the repo .venv for the local CI gates."
  cat >&2 <<'EOF'
The ruff gate needs ruff from the repo .venv (created by scripts/test.sh).
Fix one of:
  1) Install a supported Python (3.11-3.13) reachable on PATH.
  2) Pin the base interpreter in scripts/ci/env.local — rerun
     scripts/install-hooks.sh to generate it, or add by hand:
       export HERMES_WEBUI_TEST_PYTHON=/path/to/python3.1x
  3) Run ./scripts/test.sh once manually to see the underlying failure.
Failing closed: a gate that cannot run must not report success.
EOF
}

_ci_run_test_sh_version() {
  (cd "$ROOT" && ./scripts/test.sh --version)
}

# pre-commit repair path: only pays the test.sh cost when .venv is missing.
# Respects env.local's HERMES_WEBUI_TEST_PYTHON (sourced above, inherited by
# the test.sh child process).
ensure_venv() {
  if [[ -n "${VENV_PY:-}" ]]; then
    return 0
  fi
  local log ok=0
  log="$(mktemp "${TMPDIR:-/tmp}/hermes-venv-repair.XXXXXX.log")"
  ci_info ".venv missing — auto-repairing via ./scripts/test.sh --version ..."
  if _ci_run_test_sh_version >"$log" 2>&1; then
    VENV_PY="$(resolve_venv_python || true)"
    if [[ -n "$VENV_PY" ]]; then
      ci_info ".venv ready: $VENV_PY"
      ok=1
    fi
  fi
  if (( ok )); then
    rm -f "$log"
    return 0
  fi
  echo "--- tail of ./scripts/test.sh --version output ---" >&2
  tail -n 20 "$log" >&2 || true
  rm -f "$log"
  _ci_venv_guidance
  return 1
}

# pre-push variant: ALWAYS run the idempotent ensure — ./scripts/test.sh
# --version also installs any dev test dependencies missing from .venv, not
# just the interpreter, so the shards below cannot die on an absent plugin.
ensure_venv_deps() {
  if [[ -z "${VENV_PY:-}" ]]; then
    ensure_venv
    return $?
  fi
  local log
  log="$(mktemp "${TMPDIR:-/tmp}/hermes-venv-check.XXXXXX.log")"
  if ! _ci_run_test_sh_version >"$log" 2>&1; then
    echo "--- tail of ./scripts/test.sh --version output ---" >&2
    tail -n 20 "$log" >&2 || true
    rm -f "$log"
    _ci_venv_guidance
    return 1
  fi
  rm -f "$log"
  return 0
}

# --- CI-mirroring gates (tests.yml "lint" job) ------------------------------------
# NOTE on return codes: hooks call these as `gate_x || rc=1`, which suppresses
# errexit inside the function body — every fallible command below is therefore
# explicitly guarded and the function returns an explicit status.

# Whole-tree Python syntax gate. Mirrors the CI step exactly — same file list,
# unconditional and whole-tree (NOT diff-scoped): a SyntaxError whose
# parser-reported line sits on an untouched line can slip a diff filter and
# only surface as every shard failing at the conftest server-boot fixture
# (#4641). The venv python is preferred; any python3 is acceptable as it is
# only parsing, never importing.
gate_compileall() {
  local py
  py="${1:-$(ci_python)}"
  if (cd "$ROOT" && "$py" -m compileall -q api server.py bootstrap.py mcp_server.py tests scripts); then
    ci_pass "compileall: whole-tree Python syntax gate OK ($py)."
    return 0
  fi
  ci_fail "compileall: whole-tree Python syntax gate FAILED (see the file:line above)."
  return 1
}

# Ruff forward gate over COMMITTED content — the exact CI command, run with the
# venv interpreter (it has ruff installed, so ruff_lint.py's `python -m ruff`
# fallback resolves there). origin/master is fetched best-effort when missing;
# if it still cannot be resolved the gate SKIPS non-blocking: compileall still
# blocks syntax errors, and CI runs this gate server-side after the push.
gate_ruff_diff() {
  ensure_venv || return 1
  if ! git -C "$ROOT" rev-parse --verify --quiet origin/master >/dev/null 2>&1; then
    ci_info "origin/master ref missing — best-effort 'git fetch --no-tags --depth=1 origin master'..."
    git -C "$ROOT" fetch --no-tags --depth=1 origin master >/dev/null 2>&1 || true
  fi
  if ! git -C "$ROOT" rev-parse --verify --quiet origin/master >/dev/null 2>&1; then
    ci_skip "ruff forward gate: origin/master not available (offline / no upstream) — skipping, non-blocking."
    return 0
  fi
  if (cd "$ROOT" && "$VENV_PY" scripts/ruff_lint.py --diff origin/master); then
    ci_pass "ruff forward gate (committed content vs origin/master): OK."
    return 0
  fi
  ci_fail "ruff forward gate (committed content vs origin/master): FAILED — fix the flagged new/changed lines."
  return 1
}
